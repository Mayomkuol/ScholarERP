<script>

document.addEventListener('DOMContentLoaded', function () {

    const classSelect =
        document.getElementById('school_class_id');

    const streamSelect =
        document.getElementById('stream_id');

    if (!classSelect || !streamSelect) {
        return;
    }


    /*
    |--------------------------------------------------------------------------
    | Remember the stream selected before validation failed
    |--------------------------------------------------------------------------
    */

    const oldStream =
        "{{ old('stream_id') }}";


    /*
    |--------------------------------------------------------------------------
    | Filter streams according to class
    |--------------------------------------------------------------------------
    */

    function filterStreams(resetStream = false) {

        const selectedClass =
            classSelect.value;

        const options =
            streamSelect.querySelectorAll('option[data-class]');


        options.forEach(function (option) {

            const belongsToClass =
                selectedClass &&
                option.dataset.class === selectedClass;

            option.hidden = !belongsToClass;

        });


        /*
        |--------------------------------------------------------------------------
        | No class selected
        |--------------------------------------------------------------------------
        */

        if (!selectedClass) {

            streamSelect.disabled = true;

            streamSelect.value = '';

            return;

        }


        /*
        |--------------------------------------------------------------------------
        | Class selected
        |--------------------------------------------------------------------------
        */

        streamSelect.disabled = false;


        /*
        |--------------------------------------------------------------------------
        | Reset stream when user changes class
        |--------------------------------------------------------------------------
        */

        if (resetStream) {

            streamSelect.value = '';

            return;

        }


        /*
        |--------------------------------------------------------------------------
        | Restore old stream after validation error
        |--------------------------------------------------------------------------
        */

        if (oldStream) {

            const oldOption =
                streamSelect.querySelector(
                    'option[value="' + oldStream + '"]'
                );

            if (
                oldOption &&
                !oldOption.hidden
            ) {

                streamSelect.value = oldStream;

            }

        }

    }


    /*
    |--------------------------------------------------------------------------
    | Class changed
    |--------------------------------------------------------------------------
    */

    classSelect.addEventListener(
        'change',
        function () {

            filterStreams(true);

        }
    );


    /*
    |--------------------------------------------------------------------------
    | Initial page load
    |--------------------------------------------------------------------------
    */

    filterStreams(false);

});


/*
|--------------------------------------------------------------------------
| Student photo preview
|--------------------------------------------------------------------------
*/

function previewImage(event)
{

    const file =
        event.target.files[0];

    if (!file) {
        return;
    }


    const preview =
        document.getElementById('preview');


    const reader =
        new FileReader();


    reader.onload = function ()
    {

        preview.src =
            reader.result;

    };


